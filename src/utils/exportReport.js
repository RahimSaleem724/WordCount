/**
 * Utilities for formatting, copying, and downloading statistics reports in TXT and CSV formats.
 */

/**
 * Generate a formatted plain text summary of the statistics.
 *
 * @param {Object} stats
 * @returns {string}
 */
export function generateTextReport(stats) {
  const timestamp = new Date().toLocaleString();

  const lines = [
    `==================================================`,
    ` WORD & CHARACTER COUNTER REPORT`,
    ` الفاظ اور حروف شمار کنندہ رپورٹ`,
    ` Generated: ${timestamp}`,
    `==================================================`,
    ``,
    `CORE STATISTICS:`,
    `--------------------------------------------------`,
    `Words:                     ${stats.words}`,
    `Characters (with spaces):  ${stats.charactersWithSpaces}`,
    `Characters (no spaces):    ${stats.charactersWithoutSpaces}`,
    `Sentences:                 ${stats.sentences}`,
    `Paragraphs:                ${stats.paragraphs}`,
    `Lines:                     ${stats.lines}`,
    `Unique Words:              ${stats.uniqueWords}`,
    `Average Word Length:       ${stats.averageWordLength} chars`,
    `Longest Word:              ${stats.longestWord || 'N/A'}`,
    `Estimated Reading Time:    ${stats.readingTimeText} (Speed: ${stats.readingWpm} WPM)`,
    `Estimated Speaking Time:   ${stats.speakingTimeText} (Speed: ${stats.speakingWpm} WPM)`,
    `Dominant Script:           ${stats.dominantScript === 'urdu' ? 'Urdu / Arabic (RTL)' : 'Latin / English (LTR)'}`,
    ``,
    `SCRIPT BREAKDOWN:`,
    `--------------------------------------------------`,
    `Urdu/Arabic Characters:    ${stats.scriptBreakdown.urdu.count} (${stats.scriptBreakdown.urdu.percentage}%)`,
    `Latin/English Characters:  ${stats.scriptBreakdown.latin.count} (${stats.scriptBreakdown.latin.percentage}%)`,
    `Digits (0-9, ۰-۹):         ${stats.scriptBreakdown.digits.count} (${stats.scriptBreakdown.digits.percentage}%)`,
    `Other (Symbols/Punct):     ${stats.scriptBreakdown.other.count} (${stats.scriptBreakdown.other.percentage}%)`,
    ``
  ];

  if (stats.keywords && stats.keywords.length > 0) {
    lines.push(`TOP KEYWORDS:`);
    lines.push(`--------------------------------------------------`);
    lines.push(`Rank | Word                | Count | Density`);
    stats.keywords.forEach((k, idx) => {
      const rank = String(idx + 1).padEnd(4, ' ');
      const word = k.word.padEnd(20, ' ');
      const count = String(k.count).padStart(5, ' ');
      const pct = `${k.percentage}%`.padStart(7, ' ');
      lines.push(`${rank}| ${word}| ${count} | ${pct}`);
    });
    lines.push(``);
  }

  lines.push(`==================================================`);
  lines.push(`Report generated by Word & Character Counter Web App`);
  lines.push(`==================================================`);

  return lines.join('\n');
}

/**
 * Generate CSV formatted report string.
 *
 * @param {Object} stats
 * @returns {string}
 */
export function generateCsvReport(stats) {
  const rows = [
    ['Metric', 'Value', 'Unit/Percentage'],
    ['Words', stats.words, 'words'],
    ['Characters (with spaces)', stats.charactersWithSpaces, 'characters'],
    ['Characters (without spaces)', stats.charactersWithoutSpaces, 'characters'],
    ['Sentences', stats.sentences, 'sentences'],
    ['Paragraphs', stats.paragraphs, 'paragraphs'],
    ['Lines', stats.lines, 'lines'],
    ['Unique Words', stats.uniqueWords, 'unique words'],
    ['Average Word Length', stats.averageWordLength, 'characters'],
    ['Longest Word', `"${(stats.longestWord || '').replace(/"/g, '""')}"`, ''],
    ['Reading Time', `"${stats.readingTimeText}"`, `${stats.readingWpm} WPM`],
    ['Speaking Time', `"${stats.speakingTimeText}"`, `${stats.speakingWpm} WPM`],
    ['Dominant Script', stats.dominantScript, ''],
    ['Urdu Characters', stats.scriptBreakdown.urdu.count, `${stats.scriptBreakdown.urdu.percentage}%`],
    ['Latin Characters', stats.scriptBreakdown.latin.count, `${stats.scriptBreakdown.latin.percentage}%`],
    ['Digits', stats.scriptBreakdown.digits.count, `${stats.scriptBreakdown.digits.percentage}%`],
    ['Other Characters', stats.scriptBreakdown.other.count, `${stats.scriptBreakdown.other.percentage}%`]
  ];

  if (stats.keywords && stats.keywords.length > 0) {
    rows.push([]);
    rows.push(['Keyword', 'Frequency Count', 'Density %']);
    stats.keywords.forEach((k) => {
      rows.push([`"${k.word.replace(/"/g, '""')}"`, k.count, `${k.percentage}%`]);
    });
  }

  return rows.map((r) => r.join(',')).join('\n');
}

/**
 * Trigger download of content as a file in the browser.
 *
 * @param {string} content
 * @param {string} filename
 * @param {string} mimeType
 */
export function downloadFile(content, filename, mimeType = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
